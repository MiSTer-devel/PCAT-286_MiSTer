#!/usr/bin/env python3
"""Build and reproducibly check the PCAT-286 I4 event diagnostic ROM."""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests" / "firmware" / "pcat286_event_diag.asm"
ROM = ROOT / "tests" / "firmware" / "pcat286_event_diag.rom"
HEX = ROOT / "tests" / "firmware" / "pcat286_event_diag.hex"
SVH = ROOT / "tests" / "firmware" / "pcat286_event_diag_rom_case.svh"
METADATA = ROOT / "tests" / "firmware" / "pcat286_event_diag.json"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_into(directory: Path) -> tuple[bytes, bytes, bytes, bytes]:
    rom_path = directory / ROM.name
    listing_path = directory / "pcat286_event_diag.lst"
    subprocess.run(
        ["nasm", "-f", "bin", "-l", str(listing_path), "-o", str(rom_path), str(SOURCE)],
        check=True,
    )
    rom = rom_path.read_bytes()
    if len(rom) != 65536:
        raise ValueError(f"event diagnostic ROM is {len(rom)} bytes, expected 65536")
    hex_image = ("\n".join(f"{byte:02x}" for byte in rom) + "\n").encode("ascii")
    case_lines = [
        "// Generated by scripts/build_event_diag_rom.py; do not edit.",
        "function automatic logic [7:0] event_rom_read(input logic [15:0] address);",
        "    begin",
        "        case (address)",
    ]
    case_lines.extend(
        f"            16'h{address:04x}: event_rom_read = 8'h{byte:02x};"
        for address, byte in enumerate(rom)
        if byte != 0xff
    )
    case_lines.extend(
        [
            "            default: event_rom_read = 8'hff;",
            "        endcase",
            "    end",
            "endfunction",
            "",
        ]
    )
    case_image = "\n".join(case_lines).encode("ascii")
    metadata = {
        "schema_version": 1,
        "artifact": "PCAT-286 I4 event diagnostic ROM",
        "format": "raw 64 KiB ROM loaded at XT F0000-FFFFF",
        "source": SOURCE.relative_to(ROOT).as_posix(),
        "source_sha256": sha256(SOURCE.read_bytes()),
        "rom": ROM.relative_to(ROOT).as_posix(),
        "rom_sha256": sha256(rom),
        "rom_size": len(rom),
        "simulation_case": SVH.relative_to(ROOT).as_posix(),
        "simulation_case_sha256": sha256(case_image),
        "reset_vector_offset": "0xfff0",
        "pic_vector": "0x20",
        "pic_irq": 0,
        "success_port": "0x0080",
        "success_sequence": ["0x70", "0x72", "0x71", "0x86"],
        "controlled_nmi_simulation_extra": ["0x73"],
        "failure_port": "0x0081",
        "memory_signature": {
            "physical_0x10600": "0xa55a",
            "physical_0x10604": "0x2864",
            "physical_0x10606_after_controlled_nmi": "0x2bad",
        },
        "builder": "NASM flat binary, BITS 16, ORG 0",
    }
    metadata_bytes = (json.dumps(metadata, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return rom, hex_image, case_image, metadata_bytes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="pcat286-event-diag-") as temp:
        outputs = build_into(Path(temp))

    targets = tuple(zip((ROM, HEX, SVH, METADATA), outputs))
    if args.check:
        stale = [path for path, expected in targets if not path.is_file() or path.read_bytes() != expected]
        for path in stale:
            print(f"STALE {path.relative_to(ROOT)}")
        if stale:
            return 1
        print(f"EVENT_DIAGNOSTIC_ROM_CHECK_PASS sha256={sha256(outputs[0])} size={len(outputs[0])}")
        return 0

    for path, data in targets:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"EVENT_DIAGNOSTIC_ROM_BUILD_PASS sha256={sha256(outputs[0])} size={len(outputs[0])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
