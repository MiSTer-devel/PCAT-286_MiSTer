#!/usr/bin/env python3
"""Build and reproducibly check the project-owned 64 KiB diagnostic ROM."""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tests" / "firmware" / "pcat286_diag.asm"
ROM = ROOT / "tests" / "firmware" / "pcat286_diag.rom"
HEX = ROOT / "tests" / "firmware" / "pcat286_diag.hex"
SVH = ROOT / "tests" / "firmware" / "pcat286_diag_rom_case.svh"
METADATA = ROOT / "tests" / "firmware" / "pcat286_diag.json"


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_into(directory: Path) -> tuple[bytes, bytes, bytes, bytes]:
    rom_path = directory / "pcat286_diag.rom"
    listing_path = directory / "pcat286_diag.lst"
    subprocess.run(
        [
            "nasm",
            "-f",
            "bin",
            "-l",
            str(listing_path),
            "-o",
            str(rom_path),
            str(SOURCE),
        ],
        check=True,
    )
    rom = rom_path.read_bytes()
    if len(rom) != 65536:
        raise ValueError(f"diagnostic ROM is {len(rom)} bytes, expected 65536")
    hex_image = ("\n".join(f"{byte:02x}" for byte in rom) + "\n").encode("ascii")
    case_lines = [
        "// Generated by scripts/build_diag_rom.py; do not edit.",
        "function automatic logic [7:0] diagnostic_rom_read(input logic [15:0] address);",
        "    begin",
        "        case (address)",
    ]
    case_lines.extend(
        f"            16'h{address:04x}: diagnostic_rom_read = 8'h{byte:02x};"
        for address, byte in enumerate(rom)
        if byte != 0xff
    )
    case_lines.extend(
        [
            "            default: diagnostic_rom_read = 8'hff;",
            "        endcase",
            "    end",
            "endfunction",
            "",
        ]
    )
    case_image = "\n".join(case_lines).encode("ascii")
    metadata = {
        "schema_version": 1,
        "artifact": "PCAT-286 project diagnostic ROM",
        "format": "raw 64 KiB ROM loaded at XT F0000-FFFFF",
        "source": str(SOURCE.relative_to(ROOT)).replace("\\", "/"),
        "source_sha256": sha256(SOURCE.read_bytes()),
        "rom": str(ROM.relative_to(ROOT)).replace("\\", "/"),
        "rom_sha256": sha256(rom),
        "rom_size": len(rom),
        "simulation_case": str(SVH.relative_to(ROOT)).replace("\\", "/"),
        "simulation_case_sha256": sha256(case_image),
        "reset_vector_offset": "0xfff0",
        "success_port": "0x0080",
        "success_sequence": ["0x10", "0x20", "0x30", "0x40", "0x50", "0x86"],
        "failure_port": "0x0081",
        "memory_signature": {"physical_0x10500": "0x2860", "physical_0x10502": "0x5a3c"},
        "builder": "NASM flat binary, BITS 16, ORG 0",
    }
    metadata_bytes = (json.dumps(metadata, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return rom, hex_image, case_image, metadata_bytes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="pcat286-diag-") as temp:
        rom, hex_image, case_image, metadata = build_into(Path(temp))

    outputs = ((ROM, rom), (HEX, hex_image), (SVH, case_image), (METADATA, metadata))
    if args.check:
        failed = False
        for path, expected in outputs:
            if not path.is_file() or path.read_bytes() != expected:
                print(f"STALE {path.relative_to(ROOT)}")
                failed = True
        if failed:
            return 1
        print(f"DIAGNOSTIC_ROM_CHECK_PASS sha256={sha256(rom)} size={len(rom)}")
        return 0

    for path, data in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    print(f"DIAGNOSTIC_ROM_BUILD_PASS sha256={sha256(rom)} size={len(rom)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
